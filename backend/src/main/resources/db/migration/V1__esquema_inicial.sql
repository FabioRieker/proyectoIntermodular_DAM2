-- VulnFollowUp. Esquema inicial para PostgreSQL 16.
-- Flyway ejecuta cada migración dentro de una transacción.
CREATE TABLE roles (
    code varchar(16) PRIMARY KEY CHECK (code IN ('ADMIN', 'ANALYST', 'VIEWER'))
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL UNIQUE CHECK (email = lower(trim(email)) AND email <> ''),
    password_hash varchar(100) NOT NULL,
    role varchar(16) NOT NULL REFERENCES roles(code),
    enabled boolean NOT NULL DEFAULT true
);

INSERT INTO roles(code) VALUES ('ADMIN'), ('ANALYST'), ('VIEWER');

CREATE TABLE providers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(40) NOT NULL UNIQUE,
    name text NOT NULL CHECK (trim(name) <> ''),
    service text NOT NULL CHECK (trim(service) <> ''),
    criticality varchar(8) NOT NULL CHECK (criticality IN ('BAJA', 'MEDIA', 'ALTA')),
    contract_ref text NOT NULL,
    review_date date NOT NULL,
    contact text NOT NULL
);

CREATE TABLE assets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(40) NOT NULL UNIQUE,
    name text NOT NULL CHECK (trim(name) <> ''),
    type text NOT NULL CHECK (trim(type) <> ''),
    owner_id bigint NOT NULL REFERENCES users(id),
    environment text NOT NULL CHECK (trim(environment) <> ''),
    active boolean NOT NULL DEFAULT true,
    provider_id bigint REFERENCES providers(id)
);

CREATE TABLE vulnerabilities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier varchar(80) NOT NULL UNIQUE CHECK (trim(identifier) <> ''),
    title text NOT NULL CHECK (trim(title) <> ''),
    description text NOT NULL CHECK (trim(description) <> ''),
    detected_on date NOT NULL,
    status varchar(32) NOT NULL DEFAULT 'ABIERTA'
        CHECK (status IN ('ABIERTA', 'PENDIENTE_DE_REMEDIACION', 'RESUELTA', 'CERRADA')),
    assignee_id bigint REFERENCES users(id),
    due_date date,
    version bigint NOT NULL DEFAULT 0
);

CREATE TABLE vulnerability_assets (
    vulnerability_id bigint NOT NULL REFERENCES vulnerabilities(id),
    asset_id bigint NOT NULL REFERENCES assets(id),
    PRIMARY KEY (vulnerability_id, asset_id)
);
CREATE INDEX vulnerability_assets_by_asset ON vulnerability_assets (asset_id, vulnerability_id);

CREATE TABLE vulnerability_references (
    vulnerability_id bigint NOT NULL REFERENCES vulnerabilities(id),
    reference text NOT NULL CHECK (trim(reference) <> ''),
    PRIMARY KEY (vulnerability_id, reference)
);

CREATE TABLE cvss_assessments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vulnerability_id bigint NOT NULL REFERENCES vulnerabilities(id),
    assessed_at timestamptz NOT NULL DEFAULT current_timestamp,
    assessor_id bigint NOT NULL REFERENCES users(id),
    cvss_version varchar(3) NOT NULL CHECK (cvss_version IN ('3.1', '4.0')),
    vector text NOT NULL,
    -- numeric sin redondeo implícito: una nota 9.84 debe dar error.
    base_score numeric NOT NULL CHECK (base_score BETWEEN 0 AND 10 AND base_score = trunc(base_score, 1)),
    severity varchar(8) GENERATED ALWAYS AS (CASE
        WHEN base_score = 0 THEN 'NINGUNA'
        WHEN base_score < 4 THEN 'BAJA'
        WHEN base_score < 7 THEN 'MEDIA'
        WHEN base_score < 9 THEN 'ALTA'
        ELSE 'CRITICA'
    END) STORED,
    CHECK (vector LIKE ('CVSS:' || cvss_version || '/%') AND split_part(vector, '/', 2) <> '')
);
CREATE INDEX cvss_assessments_latest ON cvss_assessments (vulnerability_id, assessed_at DESC, id DESC);

-- Comentarios, evidencias y trazabilidad de la remediación; el autor es la cuenta autenticada.
CREATE TABLE remediation_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vulnerability_id bigint NOT NULL REFERENCES vulnerabilities(id),
    actor_id bigint NOT NULL REFERENCES users(id),
    occurred_at timestamptz NOT NULL DEFAULT current_timestamp,
    previous_status varchar(32) NOT NULL CHECK (previous_status IN
        ('ABIERTA', 'PENDIENTE_DE_REMEDIACION', 'RESUELTA', 'CERRADA')),
    new_status varchar(32) NOT NULL CHECK (new_status IN
        ('ABIERTA', 'PENDIENTE_DE_REMEDIACION', 'RESUELTA', 'CERRADA')),
    comment text,
    evidence text,
    CHECK (previous_status <> new_status OR nullif(trim(comment), '') IS NOT NULL
           OR nullif(trim(evidence), '') IS NOT NULL)
);

